"""Generate ZMK shield files (transform, physical layout, default keymap)
from layout.py so firmware and PCB always agree."""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import layout as L  # noqa: E402

FW = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "boards", "shields", "tsuki65")

SPLIT_GAP = 0.0  # visual gap (U) between the halves in the physical layout


# visual order: per row, left keys then right keys, each left-to-right
def ordered():
    out = []
    for r in range(5):
        for side in ("L", "R"):
            row = [k for k in L.keys(side) if k["r"] == r and not k["tb"]]
            out += [(side, k) for k in sorted(row, key=lambda k: k["xv"])]
    return out


# default keymap, same order as ordered()  (row lengths 14/13/13/13/13)
BASE = """
&kp ESC   &kp N1   &kp N2   &kp N3   &kp N4    &kp N5    &kp N6     &kp N7    &kp N8    &kp N9    &kp N0    &kp MINUS &kp EQUAL &kp BSPC
&kp TAB   &kp Q    &kp W    &kp E    &kp R     &kp T     &kp Y      &kp U     &kp I     &kp O     &kp P     &kp LBKT  &kp RBKT
&kp LCTRL &kp A    &kp S    &kp D    &kp F     &kp G     &kp H      &kp J     &kp K     &kp L     &kp SEMI  &kp SQT   &kp RET
&kp LSHFT &kp Z    &kp X    &kp C    &kp V     &kp B     &kp N      &kp M     &kp COMMA &kp DOT   &kp FSLH  &kp RSHFT &kp UP
&mo 2     &kp LGUI &kp LALT &mo 1    &kp BSPC  &kp SPACE &kp SPACE  &mo 1     &kp RALT  &kp RCTRL &kp LEFT  &kp DOWN  &kp RIGHT
"""
LOWER = """
&kp GRAVE &kp F1   &kp F2   &kp F3   &kp F4    &kp F5    &kp F6     &kp F7    &kp F8    &kp F9    &kp F10   &kp F11   &kp F12   &kp DEL
&trans    &trans   &trans   &trans   &trans    &trans    &kp HOME   &kp PG_DN &kp PG_UP &kp END   &kp PSCRN &trans    &kp BSLH
&kp CAPS  &trans   &trans   &trans   &trans    &trans    &kp LEFT   &kp DOWN  &kp UP    &kp RIGHT &trans    &trans    &trans
&trans    &trans   &trans   &trans   &trans    &trans    &mkp LCLK  &mkp RCLK &mkp MCLK &trans    &trans    &trans    &kp PG_UP
&trans    &trans   &trans   &trans   &kp DEL   &trans    &trans     &trans    &trans    &trans    &kp HOME  &kp PG_DN &kp END
"""
SYSTEM = """
&bt BT_CLR &bt BT_SEL 0 &bt BT_SEL 1 &bt BT_SEL 2 &bt BT_SEL 3 &bt BT_SEL 4 &trans &trans &trans &trans &trans &trans &trans &bootloader
&trans &out OUT_USB &out OUT_BLE &trans &trans &trans &trans &trans &trans &trans &trans &trans &sys_reset
&trans &trans &trans &trans &trans &trans &trans &trans &trans &trans &trans &trans &trans
&trans &trans &trans &trans &trans &trans &trans &trans &trans &trans &trans &trans &trans
&trans &trans &trans &trans &trans &trans &trans &trans &trans &trans &trans &trans &trans
"""


def main():
    ks = ordered()
    n = len(ks)
    # ---- transform
    rows = []
    cur, line = None, []
    for side, k in ks:
        if k["r"] != cur:
            if line:
                rows.append(line)
            line, cur = [], k["r"]
        col = k["c"] + (7 if side == "R" else 0)
        line.append(f"RC({k['r']},{col})")
    rows.append(line)
    transform = "\n".join("            " + " ".join(r) for r in rows)

    # ---- physical layout (1U = 17 mm = 100)
    phys = []
    for side, k in ks:
        xv = k["xv"] - 0.5 + (SPLIT_GAP if side == "R" else 0)
        x = int(round(xv * 100))
        y = int(round(k["r"] * 100))
        phys.append(f"<&key_physical_attrs 100 100 {x:5d} {y:5d} 0 0 0>")
    phys_s = "\n            , ".join(phys)

    dtsi = f"""#include <zephyr/dt-bindings/gpio/nordic-nrf-gpio.h>
#include <dt-bindings/zmk/matrix_transform.h>
#include <physical_layouts.dtsi>

/* generated by scripts/gen_fw.py -- {n} keys, row-staggered; the 14 mm trackball is not in the matrix */

/ {{
    chosen {{
        zmk,physical-layout = &physical_layout0;
        zmk,kscan = &kscan0;
        zmk,battery = &non_lipo_battery;
    }};

    default_transform: keymap_transform_0 {{
        compatible = "zmk,matrix-transform";
        columns = <14>;
        rows = <5>;
        map = <
{transform}
        >;
    }};

    physical_layout0: physical_layout_0 {{
        compatible = "zmk,physical-layout";
        display-name = "tsuki65";
        kscan = <&kscan0>;
        transform = <&default_transform>;
        keys  //                     w   h     x     y rot rx ry
            = {phys_s}
            ;
    }};

    /* BMP Boost pin assignment is identical to torabo-tsuki LP */
    kscan0: kscan {{
        compatible = "zmk,kscan-gpio-matrix";
        diode-direction = "row2col";
        col-gpios
            = <&gpio0 22 (GPIO_ACTIVE_HIGH | GPIO_PULL_DOWN)>,
            <&gpio1 15   (GPIO_ACTIVE_HIGH | GPIO_PULL_DOWN)>,
            <&gpio0 23   (GPIO_ACTIVE_HIGH | GPIO_PULL_DOWN)>,
            <&gpio0 10   (GPIO_ACTIVE_HIGH | GPIO_PULL_DOWN)>,
            <&gpio1 0    (GPIO_ACTIVE_HIGH | GPIO_PULL_DOWN)>,
            <&gpio0 9    (GPIO_ACTIVE_HIGH | GPIO_PULL_DOWN)>,
            <&gpio1 3    (GPIO_ACTIVE_HIGH | GPIO_PULL_DOWN)>
            ;
        row-gpios
            = <&gpio0 5 (GPIO_ACTIVE_HIGH)>,
            <&gpio0 0  (GPIO_ACTIVE_HIGH)>,
            <&gpio0 30 (GPIO_ACTIVE_HIGH)>,
            <&gpio0 3  (GPIO_ACTIVE_HIGH)>,
            <&gpio1 14 (GPIO_ACTIVE_HIGH)>
            ;
        wakeup-source;
    }};

    leds {{
        compatible = "gpio-leds";
        status_led: status_led {{
            gpios = <&bmp 2 GPIO_ACTIVE_HIGH>;
            label = "Status LED";
        }};
    }};

    status_led_device: status_led_device {{
        compatible = "zmk,status-led";
        led = <&status_led>;
    }};

    bootloader_trigger: bootloader_trigger {{
        compatible = "zmk,cdc-acm-bootloader-trigger";
    }};

    pointing_listener: pointing_listener {{
        compatible = "zmk,input-listener";
        status = "disabled";
    }};

    vbatt: vbatt {{
        status = "disabled";
    }};
    non_lipo_battery: non_lipo_battery {{
        compatible = "zmk,non-lipo-battery";
        io-channels = <&adc 4>;
    }};
}};

&pinctrl {{
    spi0_default: spi0_default {{
        group1 {{
            psels = <NRF_PSEL(SPIM_SCK, 0, 18)>,
                    <NRF_PSEL(SPIM_MOSI, 0, 16)>,
                    <NRF_PSEL(SPIM_MISO, 0, 16)>;
        }};
    }};
    spi0_sleep: spi0_sleep {{
        group1 {{
            psels = <NRF_PSEL(SPIM_SCK, 0, 18)>,
                    <NRF_PSEL(SPIM_MOSI, 0, 16)>,
                    <NRF_PSEL(SPIM_MISO, 0, 16)>;
        }};
        low-power-enable;
    }};
}};
"""
    with open(os.path.join(FW, "tsuki65.dtsi"), "w") as f:
        f.write(dtsi)

    def fmt(block):
        toks = []
        for line in block.strip().splitlines():
            parts = line.split("&")[1:]
            toks += ["&" + p.strip() for p in parts]
        assert len(toks) == n, (len(toks), n)
        out, i = [], 0
        for row in rows:
            out.append("  ".join(f"{t:<14}" for t in toks[i:i + len(row)]).rstrip())
            i += len(row)
        return "\n".join(out)

    keymap = f"""/* generated by scripts/gen_fw.py -- edit freely (or use ZMK Studio) */
#include <behaviors.dtsi>
#include <dt-bindings/zmk/bt.h>
#include <dt-bindings/zmk/keys.h>
#include <dt-bindings/zmk/outputs.h>
#include <dt-bindings/zmk/pointing.h>

/ {{
    keymap {{
        compatible = "zmk,keymap";

        base {{
            bindings = <
{fmt(BASE)}
            >;
        }};

        lower {{
            bindings = <
{fmt(LOWER)}
            >;
        }};

        system {{
            bindings = <
{fmt(SYSTEM)}
            >;
        }};
    }};
}};
"""
    with open(os.path.join(FW, "tsuki65.keymap"), "w") as f:
        f.write(keymap)
    cfg = os.path.join(FW, "..", "..", "..", "config", "tsuki65.keymap")
    with open(cfg, "w") as f:
        f.write(keymap)
    print("keys:", n)


if __name__ == "__main__":
    main()
